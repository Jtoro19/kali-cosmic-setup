#!/usr/bin/env bash
# tests/test-locale.sh: modules/08-locale.sh against fake commands (apt-get,
# dpkg-query, locale, locale-gen, update-locale) and a temporary root prefix
# (KCS_ROOT). Never touches the real system.
# shellcheck disable=SC2319
set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf -- "${WORK:?}"' EXIT
# shellcheck source=tests/lib-fakes.sh
source "$REPO_ROOT/tests/lib-fakes.sh"

export FAKE_STATE="$WORK/state"
export KCS_ROOT="$WORK/root"
make_fakes "$WORK/bin"

# locale -a: prints the generated locales kept in $FAKE_STATE/locales.
cat >"$WORK/bin/locale" <<'EOS'
#!/bin/sh
[ "$1" = "-a" ] || exit 0
cat "$FAKE_STATE/locales" 2>/dev/null
EOS
# locale-gen: logs the call and "generates" every uncommented locale.gen entry.
cat >"$WORK/bin/locale-gen" <<'EOS'
#!/bin/sh
echo "locale-gen $*" >>"$FAKE_STATE/gen.log"
case "|${FAKE_FAIL:-}|" in *"|locale-gen|"*) exit 1 ;; esac
: >"$FAKE_STATE/locales"
echo C >>"$FAKE_STATE/locales"
sed -n 's/^\([a-z][a-z]_[A-Z][A-Z]\)\.UTF-8 UTF-8$/\1.utf8/p' "${KCS_ROOT:-}/etc/locale.gen" >>"$FAKE_STATE/locales"
EOS
# update-locale KEY=VALUE...: logs the call and merges the pairs into
# /etc/default/locale, keeping every other line (like the real command).
cat >"$WORK/bin/update-locale" <<'EOS'
#!/bin/sh
echo "update-locale $*" >>"$FAKE_STATE/ul.log"
case "|${FAKE_FAIL:-}|" in *"|update-locale|"*) exit 1 ;; esac
f="${KCS_ROOT:-}/etc/default/locale"
mkdir -p "$(dirname "$f")"
touch "$f"
for kv in "$@"; do
  k="${kv%%=*}"
  v="${kv#*=}"
  grep -v "^$k=" "$f" >"$f.new"
  echo "$k=\"$v\"" >>"$f.new"
  mv -- "$f.new" "$f"
done
EOS
chmod +x "$WORK/bin"/*

failures=0
check() { # check <description> <status>
  if (($2 == 0)); then
    printf 'ok   - %s\n' "$1"
  else
    printf 'FAIL - %s\n' "$1"
    failures=$((failures + 1))
  fi
}

LGEN="$KCS_ROOT/etc/locale.gen"
DEF="$KCS_ROOT/etc/default/locale"
APT="$FAKE_STATE/apt.log"

reset_state() { # reset_state [with-locales-package]
  rm -rf -- "${FAKE_STATE:?}" "${KCS_ROOT:?}"
  mkdir -p "$FAKE_STATE" "$KCS_ROOT/etc/default"
  echo locales >"$FAKE_STATE/installed"
  printf 'C\nen_US.utf8\n' >"$FAKE_STATE/locales"
  # A Debian-like locale.gen: everything commented except en_US.
  printf '%s\n' '# This file lists locales that you wish to have built.' \
    '# es_CO.UTF-8 UTF-8' '# es_ES.UTF-8 UTF-8' 'en_US.UTF-8 UTF-8' '# fr_FR.UTF-8 UTF-8' >"$LGEN"
  printf '%s\n' '#  File generated by update-locale' 'LANG="en_US.UTF-8"' 'LANGUAGE="en_US:en"' >"$DEF"
}

loc() { # loc <install.sh args...>: run the locale module; sets rc, output in $WORK/out
  rm -f -- "${FAKE_STATE:?}"/*.log
  rc=0
  PATH="$WORK/bin:$PATH" KCS_SKIP_SUDO=1 KCS_SKIP_OS_CHECK=1 XDG_CACHE_HOME="$WORK/cache" \
    "$REPO_ROOT/install.sh" --only locale "$@" >"$WORK/out" 2>&1 </dev/null || rc=$?
}

# --- dry-run ----------------------------------------------------------------
reset_state
cp -- "$LGEN" "$WORK/lgen.orig"
cp -- "$DEF" "$WORK/def.orig"
loc --dry-run
[[ "$rc" == 0 ]]
check "dry-run succeeds" $?
cmp -s "$LGEN" "$WORK/lgen.orig" && cmp -s "$DEF" "$WORK/def.orig" &&
  [[ ! -e "$FAKE_STATE/gen.log" && ! -e "$FAKE_STATE/ul.log" && ! -s "$APT" ]] &&
  ! compgen -G "$KCS_ROOT/etc/*.bak.*" >/dev/null
check "dry-run changes no file and runs no locale-gen, update-locale or apt-get" $?
grep -q '/etc/locale.gen' "$WORK/out" && grep -q 'update-locale' "$WORK/out"
check "dry-run prints the locale.gen and update-locale changes" $?

# --- real run ---------------------------------------------------------------
loc
[[ "$rc" == 0 ]]
check "real run succeeds" $?
grep -qx 'en_US.UTF-8 UTF-8' "$LGEN" && grep -qx 'es_CO.UTF-8 UTF-8' "$LGEN"
check "en_US and es_CO are enabled in locale.gen" $?
[[ "$(grep -c '^[a-z]' "$LGEN")" == 2 ]] && grep -qx '# es_ES.UTF-8 UTF-8' "$LGEN" &&
  grep -qx '# fr_FR.UTF-8 UTF-8' "$LGEN" && grep -qx '# This file lists locales that you wish to have built.' "$LGEN"
check "only the needed locales are enabled; the others and the comments are kept" $?
compgen -G "$KCS_ROOT/etc/locale.gen.bak.*" >/dev/null
check "locale.gen is backed up before the change" $?
[[ "$(wc -l <"$FAKE_STATE/gen.log")" == 1 ]]
check "locale-gen runs exactly once" $?
grep -qx 'es_CO.utf8' "$FAKE_STATE/locales"
check "es_CO.utf8 is generated" $?
want_ok=0
for kv in LANG=en_US.UTF-8 LC_ADDRESS=es_CO.UTF-8 LC_IDENTIFICATION=es_CO.UTF-8 LC_MEASUREMENT=es_CO.UTF-8 \
  LC_MONETARY=es_CO.UTF-8 LC_NAME=es_CO.UTF-8 LC_NUMERIC=es_CO.UTF-8 LC_PAPER=es_CO.UTF-8 \
  LC_TELEPHONE=es_CO.UTF-8 LC_TIME=es_CO.UTF-8; do
  grep -qx "${kv%%=*}=\"${kv#*=}\"" "$DEF" || want_ok=1
done
check "/etc/default/locale has LANG en_US and the es_CO formats" $want_ok
grep -qx 'LANGUAGE="en_US:en"' "$DEF"
check "update-locale keeps the LANGUAGE line it did not own" $?
[[ "$(wc -l <"$FAKE_STATE/ul.log")" == 1 ]]
check "update-locale runs once, with every variable in one call" $?
[[ ! -e "$KCS_ROOT/etc/default/keyboard" && ! -e "$KCS_ROOT/etc/X11" && ! -e "$KCS_ROOT/etc/locale.conf" ]]
check "the keyboard is not touched and no Arch-style /etc/locale.conf is written" $?

# --- second run changes nothing ---------------------------------------------
rm -f -- "$KCS_ROOT"/etc/*.bak.* "$KCS_ROOT"/etc/default/*.bak.*
loc
[[ "$rc" == 0 ]] && grep -q 'total changes: 0' "$WORK/out"
check "second run reports total changes: 0" $?
[[ ! -e "$FAKE_STATE/gen.log" && ! -e "$FAKE_STATE/ul.log" && ! -s "$APT" ]] &&
  ! compgen -G "$KCS_ROOT/etc/*.bak.*" >/dev/null
check "second run: no locale-gen, no update-locale, no apt-get, no backup" $?
loc --dry-run
grep -q 'Nothing to change' "$WORK/out"
check "dry-run after a real run says Nothing to change" $?

# --- locales package --------------------------------------------------------
reset_state
: >"$FAKE_STATE/installed"
loc
[[ "$rc" == 0 ]] && grep -q 'install .*locales' "$APT"
check "the locales package is installed when missing" $?
grep -q 'locales' "$FAKE_STATE/installed" && [[ -e "$FAKE_STATE/gen.log" ]]
check "locale-gen runs after the package is there" $?

# --- locale.gen without the entries (appended) and a missing file -----------
reset_state
printf '%s\n' '# nothing wanted here' >"$LGEN"
loc
grep -qx 'en_US.UTF-8 UTF-8' "$LGEN" && grep -qx 'es_CO.UTF-8 UTF-8' "$LGEN" && [[ -e "$FAKE_STATE/gen.log" ]]
check "entries missing from locale.gen are appended" $?
reset_state
rm -f -- "$LGEN"
loc
[[ "$rc" == 0 ]] && grep -qx 'es_CO.UTF-8 UTF-8' "$LGEN"
check "a missing locale.gen is created with the wanted locales" $?

# --- already generated and configured, but one locale was never generated ---
reset_state
loc
printf 'C\nen_US.utf8\n' >"$FAKE_STATE/locales"
loc
[[ "$rc" == 0 ]] && [[ -e "$FAKE_STATE/gen.log" ]] && [[ ! -e "$FAKE_STATE/ul.log" ]] && grep -q 'total changes: 1' "$WORK/out"
check "a locale missing from 'locale -a' triggers locale-gen only (1 change)" $?

# --- stale value in /etc/default/locale -------------------------------------
reset_state
loc
sed -i 's/^LC_TIME=.*/LC_TIME="en_US.UTF-8"/' "$DEF"
loc
grep -qx 'LC_TIME="es_CO.UTF-8"' "$DEF" && [[ ! -e "$FAKE_STATE/gen.log" ]] && grep -q 'total changes: 1' "$WORK/out"
check "a stale LC_TIME is corrected; nothing else is redone" $?
reset_state
printf 'LANG=en_US.UTF-8\n' >"$DEF"
loc
grep -qx 'LC_TIME="es_CO.UTF-8"' "$DEF" && grep -Eqx 'LANG="?en_US.UTF-8"?' "$DEF"
check "an unquoted LANG already correct does not stop the other variables" $?
reset_state
loc
sed -i "s/^LANG=.*/LANG='en_US.UTF-8'/" "$DEF"
loc
grep -q 'total changes: 0' "$WORK/out"
check "single-quoted values are read as the same value (0 changes)" $?

# --- LC_ALL in /etc/default/locale overrides the module ----------------------
reset_state
printf '%s\n' 'LANG="en_US.UTF-8"' 'LC_ALL="C.UTF-8"' >"$DEF"
loc
[[ "$rc" == 0 ]] && grep -q '\[warn\].*LC_ALL' "$WORK/out"
check "LC_ALL set in /etc/default/locale: warns that it overrides the module" $?
reset_state
loc
! grep -q 'LC_ALL' "$WORK/out"
check "no LC_ALL in /etc/default/locale: no LC_ALL warning" $?

# --- LOCALE_TZ must be a zone file, not a directory ---------------------------
reset_state
LOCALE_TZ=America loc
[[ "$rc" != 0 ]] && grep -q 'unknown time zone' "$WORK/out"
check "LOCALE_TZ naming a zoneinfo directory is an unknown time zone" $?

# --- failures fail the module ------------------------------------------------
reset_state
FAKE_FAIL='locale-gen' loc
[[ "$rc" != 0 ]] && [[ ! -e "$FAKE_STATE/ul.log" ]]
check "a failing locale-gen fails the module before update-locale" $?
reset_state
FAKE_FAIL='update-locale' loc
[[ "$rc" != 0 ]]
check "a failing update-locale fails the module" $?

# --- data file ---------------------------------------------------------------
[[ "$(grep -c . "$REPO_ROOT/files/locale/locale.conf")" == 10 ]] && ! grep -rq "$(printf '\342\200\224')" "$REPO_ROOT/modules/08-locale.sh" "$REPO_ROOT/specs/locale.md" 2>/dev/null
check "files/locale/locale.conf has the 10 variables; no em dash in the module or spec" $?

if ((failures > 0)); then
  printf '\n--- last install.sh output ---\n'
  cat -- "$WORK/out"
  printf '%d check(s) failed\n' "$failures"
  exit 1
fi
printf 'all checks passed\n'
